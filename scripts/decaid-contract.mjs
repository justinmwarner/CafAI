#!/usr/bin/env node
// Decaid's pinned specs and the types generated from them (D93, D94; spec 4.1).
//
//   --update <tag|sha>  resolve the ref on GitHub, download both specs at that
//                       commit into contract/decaid/spec/, regenerate, rewrite
//                       PIN.json and src/api/decaidVersion.ts, print what changed
//   --check             the vendored specs match PIN.json's hashes and
//                       regenerating them gives the committed files; exit 1
//                       naming the stale files otherwise (part of typecheck)
//
// REST types come from openapi-typescript's Node API, never with --enum (it
// emits TypeScript enums, which erasableSyntaxOnly forbids). The AsyncAPI file
// is self-contained and written in OpenAPI 3.0's dialect (`nullable`), so its
// components.schemas are wrapped in a stub OpenAPI 3.0 document and run
// through the same generator, followed by the channel map kept below. Output
// is .ts, not .d.ts, because skipLibCheck would skip a .d.ts.
//
// Line endings are compared as LF: git checks these files out with LF
// (.gitattributes), and a CRLF copy is not a different contract.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const REPO = 'decentespresso/decaid';
/** Where the specs live in Decaid's repository. */
export const UPSTREAM = { rest: 'assets/api/rest_v1.yml', ws: 'assets/api/websocket_v1.yml' };

/** The contract's files, relative to the repository root, with forward slashes. */
export const FILES = {
  pin: 'contract/decaid/PIN.json',
  restSpec: 'contract/decaid/spec/rest_v1.yml',
  wsSpec: 'contract/decaid/spec/websocket_v1.yml',
  rest: 'contract/decaid/generated/rest.ts',
  ws: 'contract/decaid/generated/ws.ts',
  version: 'src/api/decaidVersion.ts',
};

const GENERATOR = `openapi-typescript@${JSON.parse(readFileSync(path.join(ROOT, 'node_modules/openapi-typescript/package.json'), 'utf8')).version}`;

/**
 * Each channel's frames by schema name: `receive` is what Decaid pushes,
 * `send` what a client may send (AsyncAPI operations with action receive and
 * send; the spec is written from the client's side). Kept by hand so a new or
 * changed channel is a reviewed change; scripts/decaid-contract.test.mjs
 * checks it against the pinned spec.
 */
export const CHANNELS = {
  'ws/v1/machine/snapshot': { receive: ['MachineSnapshot'] },
  'ws/v1/machine/shotSettings': { receive: ['ShotSettings'] },
  'ws/v1/machine/waterLevels': { receive: ['WaterLevels'] },
  'ws/v1/machine/shotState': { receive: ['ShotStateEvent'] },
  'ws/v1/machine/raw': { receive: ['De1RawMessage', 'MachineRawError'], send: ['De1RawMessage'] },
  'ws/v1/scale/snapshot': { receive: ['ScaleSnapshot', 'ScaleStatus'] },
  'ws/v1/scales/{id}/snapshot': { receive: ['AddressedScaleSnapshot', 'ScaleStatus'] },
  'ws/v1/grinder/snapshot': { receive: ['GrinderSnapshot'] },
  'ws/v1/sensors/{id}/snapshot': { receive: ['SensorSnapshot'] },
  'ws/v1/plugins/{id}/{endpoint}': { receive: ['PluginMessage'] },
  'ws/v1/devices': { receive: ['DevicesState', 'DeviceConnectResult'], send: ['DevicesCommand'] },
  'ws/v1/display': { receive: ['DisplayState'], send: ['DisplayCommand'] },
  'ws/v1/update': { receive: ['AppUpdateState'], send: ['UpdateCommand'] },
  'ws/v1/logs': { receive: ['LogMessage'] },
  'ws/v1/webview/logs': { receive: ['LogMessage'] },
};

export const lf = (text) => text.replace(/\r\n/g, '\n');
export const sha256 = (text) => createHash('sha256').update(lf(text), 'utf8').digest('hex');

const header = (commit, source) =>
  `// Generated by scripts/decaid-contract.mjs from Decaid ${commit}. Do not edit.\n// ${source}\n\n`;

/** generated/rest.ts from rest_v1.yml's text. */
export async function generateRest(text, commit) {
  const ast = await openapiTS(lf(text), { silent: true });
  return header(commit, `Source: ${UPSTREAM.rest} (OpenAPI), through ${GENERATOR}.`) + astToString(ast);
}

/** The channel map the spec itself declares, by address (for the test and the drift watch). */
export function specChannels(doc) {
  const deref = (ref) =>
    String(ref)
      .replace(/^#\//, '')
      .split('/')
      .reduce((node, key) => node?.[key.replace(/~1/g, '/').replace(/~0/g, '~')], doc);
  const out = {};
  for (const op of Object.values(doc.operations ?? {})) {
    const channel = deref(op.channel.$ref);
    const messages = op.messages ? op.messages.map((message) => deref(message.$ref)) : Object.values(channel.messages ?? {});
    const entry = (out[channel.address] ??= {});
    for (const message of messages) {
      const resolved = message.$ref ? deref(message.$ref) : message;
      const name = String(resolved.payload?.$ref ?? '').replace(/^#\/components\/schemas\//, '');
      const list = (entry[op.action] ??= []);
      if (name && !list.includes(name)) list.push(name);
    }
  }
  return out;
}

/** generated/ws.ts from websocket_v1.yml's text. */
export async function generateWs(text, commit, channels = CHANNELS) {
  const doc = parse(lf(text));
  if (!String(doc.asyncapi).startsWith('3.')) throw new Error(`expected AsyncAPI 3.x, got ${doc.asyncapi}`);
  const stub = {
    openapi: '3.0.3',
    info: { title: `${doc.info.title} (WebSocket payload schemas)`, version: doc.info.version },
    paths: {},
    components: { schemas: doc.components.schemas },
  };
  const types = astToString(await openapiTS(stub, { silent: true }));
  const union = (names) => names.map((name) => `components["schemas"]["${name}"]`).join(' | ');
  const map = (title, action) => {
    const lines = [title, `export interface Ws${action === 'receive' ? 'Receive' : 'Send'} {`];
    for (const [address, entry] of Object.entries(channels)) {
      if (entry[action]?.length) lines.push(`    "${address}": ${union(entry[action])};`);
    }
    return [...lines, '}'].join('\n');
  };
  return (
    header(
      commit,
      `Source: ${UPSTREAM.ws} (AsyncAPI ${doc.asyncapi}): its schemas as OpenAPI 3.0 through ${GENERATOR}, and CHANNELS from the script.`,
    ) +
    types +
    '\n' +
    map('/** What Decaid pushes on each channel, by address. */', 'receive') +
    '\n' +
    map('/** What a client may send on a channel. */', 'send') +
    '\nexport type WsChannel = keyof WsReceive;\n'
  );
}

/** src/api/decaidVersion.ts. */
export function versionModule(release, commit) {
  const version = release === null ? 'null' : `'${release.replace(/^v/, '')}'`;
  return (
    "// Written by scripts/decaid-contract.mjs; do not edit.\n" +
    "/** The Decaid release CafAI's wire types were checked against (D93). */\n" +
    `export const VERIFIED_DECAID = { release: ${version}, commit: '${commit.slice(0, 7)}' } as const;\n`
  );
}

export function pinJson(release, commit, restText, wsText) {
  const pin = {
    release,
    commit,
    specs: {
      rest: { file: 'spec/rest_v1.yml', sha256: sha256(restText) },
      ws: { file: 'spec/websocket_v1.yml', sha256: sha256(wsText) },
    },
    generator: GENERATOR,
  };
  return JSON.stringify(pin, null, 2) + '\n';
}

/** Every generated file, by its path in FILES. */
export async function generateAll({ release, commit, restText, wsText }) {
  return {
    [FILES.rest]: await generateRest(restText, commit),
    [FILES.ws]: await generateWs(wsText, commit),
    [FILES.version]: versionModule(release, commit),
  };
}

const read = (base, file) => {
  const full = path.join(base, ...file.split('/'));
  return existsSync(full) ? lf(readFileSync(full, 'utf8')) : null;
};

/** The stale files under `base` (a checkout's root), as "file: why"; [] when the contract is current. */
export async function checkContract(base = ROOT) {
  const pinText = read(base, FILES.pin);
  if (pinText === null) return [`${FILES.pin}: missing (run npm run decaid:update -- <tag>)`];
  const pin = JSON.parse(pinText);
  const stale = [];
  const restText = read(base, FILES.restSpec);
  const wsText = read(base, FILES.wsSpec);
  if (restText === null || sha256(restText) !== pin.specs.rest.sha256) stale.push(`${FILES.restSpec}: does not match PIN.json`);
  if (wsText === null || sha256(wsText) !== pin.specs.ws.sha256) stale.push(`${FILES.wsSpec}: does not match PIN.json`);
  if (pin.generator !== GENERATOR) stale.push(`${FILES.pin}: generated with ${pin.generator}, ${GENERATOR} is installed`);
  if (stale.length > 0) return stale;
  const expected = await generateAll({ release: pin.release, commit: pin.commit, restText, wsText });
  for (const [file, text] of Object.entries(expected)) {
    if (read(base, file) !== text) stale.push(`${file}: differs from what the pinned specs generate`);
  }
  return stale;
}

/** A hung child process (tsc, vitest) is stopped after this long; a normal run takes well under a minute. */
export const CHILD_TIMEOUT_MS = 10 * 60_000;

/** A child process's output, or why it stopped without finishing. */
export function childOutput(result, what) {
  const output = `${result.stdout ?? ''}${result.stderr ?? ''}`.trim();
  if (result.error?.code === 'ETIMEDOUT') return `${what} did not finish within ${CHILD_TIMEOUT_MS / 60_000} minutes. ${output}`.trim();
  if (result.error) return `${what} could not run (${result.error.message}). ${output}`.trim();
  if (result.signal) return `${what} was stopped (${result.signal}). ${output}`.trim();
  return output;
}

/**
 * The contract typecheck against generated files in `dir` (rest.ts and ws.ts)
 * instead of the pinned ones: a tsconfig there extends tsconfig.contract.json
 * and points the #decaid aliases at them. The drift watch and the mutation
 * test use it. Answers tsc's verdict and output.
 */
export function contractTypecheck(dir) {
  const posix = (file) => file.split(path.sep).join('/');
  const config = {
    extends: posix(path.join(ROOT, 'tsconfig.contract.json')),
    compilerOptions: {
      paths: { '#decaid/rest': [posix(path.join(dir, 'rest.ts'))], '#decaid/ws': [posix(path.join(dir, 'ws.ts'))] },
      // Type libraries resolve from the config's folder; the checks need Node's only.
      typeRoots: [posix(path.join(ROOT, 'node_modules', '@types'))],
      types: ['node'],
    },
    include: [`${posix(ROOT)}/contract/decaid/**/*.ts`],
    exclude: [`${posix(ROOT)}/contract/decaid/generated/**`],
  };
  const tsconfig = path.join(dir, 'tsconfig.json');
  writeFileSync(tsconfig, JSON.stringify(config, null, 2) + '\n');
  const tsc = path.join(ROOT, 'node_modules', 'typescript', 'bin', 'tsc');
  const result = spawnSync(process.execPath, [tsc, '-p', tsconfig, '--noEmit', '--noErrorTruncation'], {
    cwd: ROOT,
    encoding: 'utf8',
    timeout: CHILD_TIMEOUT_MS,
  });
  return { ok: result.status === 0, output: childOutput(result, 'tsc') };
}

