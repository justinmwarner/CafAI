/** GitHub could not be reached, or answered something unusable. */
export class GitHubError extends Error {
  constructor(message, status = null) {
    super(message);
    this.name = 'GitHubError';
    this.status = status;
  }
}

/** A spec file Decaid's repository does not have at a commit (404): it moved or was removed. */
export class SpecMissingError extends Error {
  constructor(file, sha) {
    super(`Decaid no longer serves ${file} at ${String(sha).slice(0, 7)}`);
    this.name = 'SpecMissingError';
    this.file = file;
    this.sha = sha;
  }
}

const cache = new Map();

/** GET api.github.com/<pathname> as JSON, once per run (unauthenticated calls are limited to 60 an hour). */
export async function github(pathname, { allow404 = false } = {}) {
  if (cache.has(pathname)) return cache.get(pathname);
  const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
  let response;
  try {
    response = await fetch(`https://api.github.com/${pathname}`, {
      headers: {
        accept: 'application/vnd.github+json',
        'user-agent': 'cafai-decaid-contract',
        ...(token ? { authorization: `Bearer ${token}` } : {}),
      },
      signal: AbortSignal.timeout(30_000),
    });
  } catch (error) {
    throw new GitHubError(`GitHub could not be reached (${error.message})`);
  }
  if (allow404 && response.status === 404) {
    cache.set(pathname, null);
    return null;
  }
  if (!response.ok) {
    const limited = response.headers.get('x-ratelimit-remaining') === '0' ? ' (rate limit: set GH_TOKEN)' : '';
    throw new GitHubError(`GitHub answered ${response.status} for ${pathname}${limited}`, response.status);
  }
  const body = await response.json();
  cache.set(pathname, body);
  return body;
}

/** A tag, branch or sha to `{ sha, tag }` (`tag` null unless the ref is a tag). */
export async function resolveRef(ref) {
  const isSha = /^[0-9a-f]{7,40}$/i.test(ref);
  const tag = isSha ? null : await github(`repos/${REPO}/git/ref/tags/${encodeURIComponent(ref)}`, { allow404: true });
  const commit = await github(`repos/${REPO}/commits/${encodeURIComponent(ref)}`);
  if (typeof commit?.sha !== 'string') throw new GitHubError(`GitHub sent no commit for ${ref}`);
  return { sha: commit.sha, tag: tag ? ref : null };
}

/** Both specs' text at a commit. */
export async function fetchSpecs(sha, { fetch: fetchImpl = globalThis.fetch } = {}) {
  const get = async (file) => {
    let response;
    try {
      response = await fetchImpl(`https://raw.githubusercontent.com/${REPO}/${sha}/${file}`, { signal: AbortSignal.timeout(60_000) });
    } catch (error) {
      throw new GitHubError(`GitHub could not be reached (${error.message})`);
    }
    // A 404 is Decaid's answer, not GitHub's trouble: the spec moved or is gone at that commit.
    if (response.status === 404) throw new SpecMissingError(file, sha);
    if (!response.ok) throw new GitHubError(`GitHub answered ${response.status} for ${file} at ${sha}`, response.status);
    return response.text();
  };
  return { restText: await get(UPSTREAM.rest), wsText: await get(UPSTREAM.ws) };
}

// ---------------------------------------------------------------------------
// The commands
// ---------------------------------------------------------------------------

function write(file, text) {
  const full = path.join(ROOT, ...file.split('/'));
  mkdirSync(path.dirname(full), { recursive: true });
  writeFileSync(full, text);
}

async function update(ref) {
  const { sha, tag } = await resolveRef(ref);
  const { restText, wsText } = await fetchSpecs(sha);
  const before = read(ROOT, FILES.pin);
  const outputs = {
    [FILES.restSpec]: restText,
    [FILES.wsSpec]: wsText,
    ...(await generateAll({ release: tag, commit: sha, restText, wsText })),
    [FILES.pin]: pinJson(tag, sha, restText, wsText),
  };
  const changed = Object.entries(outputs).filter(([file, text]) => read(ROOT, file) !== lf(text));
  for (const [file, text] of changed) write(file, text);
  const previous = before ? JSON.parse(before) : null;
  console.log(
    `Pinned Decaid ${tag ?? '(no tag)'} at ${sha}` +
      (previous ? ` (was ${previous.release ?? '(no tag)'} at ${previous.commit})` : ''),
  );
  console.log(changed.length ? `Changed: ${changed.map(([file]) => file).join(', ')}` : 'Nothing changed.');
  if (changed.some(([file]) => file === FILES.restSpec || file === FILES.wsSpec)) {
    console.log('The specs changed: run npm run typecheck and npx vitest run mock/decaid/contract.test.ts, then fix types.ts or drift.ts.');
  }
}

async function main(args) {
  if (args[0] === '--check') {
    const stale = await checkContract();
    if (stale.length > 0) {
      console.error(`Decaid contract is stale:\n${stale.map((line) => `  ${line}`).join('\n')}`);
      console.error('Regenerate with npm run decaid:update -- <tag>, or restore the files from git.');
      process.exit(1);
    }
    const pin = JSON.parse(read(ROOT, FILES.pin));
    console.log(`ok - the Decaid contract matches the pin (${pin.release ?? 'no tag'}, ${pin.commit.slice(0, 7)})`);
    return;
  }
  if (args[0] === '--update' && args[1]) {
    try {
      await update(args[1]);
    } catch (error) {
      if (error instanceof SpecMissingError) {
        console.error(`${error.message}: the spec moved or was removed; nothing was changed.`);
        process.exit(1);
      }
      if (!(error instanceof GitHubError)) throw error;
      console.error(error.message);
      process.exit(2);
    }
    return;
  }
  console.error('Usage: node scripts/decaid-contract.mjs --update <tag|sha> | --check');
  process.exit(2);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) await main(process.argv.slice(2));
